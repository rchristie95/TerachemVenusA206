"""Absolute interaction-induced CD of a detuned dimer, in molar units.

Absolute CD was previously treated as blocked because TeraChem was believed not
to emit magnetic transition dipoles. That premise is wrong twice over. TeraChem
DOES print them, together with length- and velocity-gauge rotational strengths,
for every root -- but they are unusable here, because the velocity dipole
violates the hypervirial relation badly enough that the two gauges disagree in
sign in 208 of 220 production runs and R(len) shifts by 100 % per 0.79 Angstrom
of gauge origin (see scripts/audit_magnetic_dipoles.py).

None of that blocks absolute CD, because in the coupled-oscillator
(exciton-chirality) mechanism the rotational strength is generated by the two
ELECTRIC transition dipoles and their spatial displacement,

    R_pm = -+ pi nubar (J/Omega) T,     T = R_AB . (mu_A x mu_B),

so electric dipoles and geometry suffice. A magnetic transition dipole is needed
only for the INTRINSIC monomer rotational strength, which cancels in the
TDX - TD difference spectrum that the experiment reports. This module therefore
closes the absolute-intensity gap without further electronic structure.

Units
-----
Inputs are the natural outputs of the pipeline: dipoles in atomic units,
positions in Angstrom, energies in cm^-1. Internally everything goes to cgs,
where a rotational strength has units erg cm^3 = esu^2 cm^2 and is conventionally
quoted in 1e-40 cgs (often written DBM).

    Delta_eps(nubar) = (1 / 2.296e-39) * sum_k R_k nubar_k g(nubar - nubar_k)

with g a normalised lineshape (integral 1 over nubar, so units of cm). The
molar ellipticity follows from Delta_theta = 3298.2 * Delta_eps.
"""

from __future__ import annotations

import numpy as np

__all__ = [
    "DEBYE_PER_AU", "CGS_PER_ANGSTROM_DEBYE2", "DELTA_EPSILON_PREFACTOR",
    "ELLIPTICITY_PER_DELTA_EPSILON",
    "triple_product_cgs", "rotational_strengths", "cd_spectrum",
    "first_moment", "shift_to_origin",
]

DEBYE_PER_AU = 2.5417464519             # 1 a.u. dipole in Debye
ANGSTROM_CM = 1.0e-8                    # 1 Angstrom in cm
DEBYE_ESU_CM = 1.0e-18                  # 1 Debye in esu cm
# Angstrom * Debye^2 -> esu^2 cm^3
CGS_PER_ANGSTROM_DEBYE2 = ANGSTROM_CM * DEBYE_ESU_CM**2
DELTA_EPSILON_PREFACTOR = 1.0 / 2.296e-39
ELLIPTICITY_PER_DELTA_EPSILON = 3298.2  # deg cm^2 dmol^-1 per M^-1 cm^-1


def triple_product_cgs(r_a_ang, r_b_ang, mu_a_au, mu_b_au):
    """T = R_AB . (mu_A x mu_B) in esu^2 cm^3, from Angstrom and atomic units."""
    r_ab = np.asarray(r_b_ang, float) - np.asarray(r_a_ang, float)
    mu_a = np.asarray(mu_a_au, float) * DEBYE_PER_AU
    mu_b = np.asarray(mu_b_au, float) * DEBYE_PER_AU
    t_ang_debye2 = np.einsum("...i,...i->...", r_ab, np.cross(mu_a, mu_b))
    return t_ang_debye2 * CGS_PER_ANGSTROM_DEBYE2


def rotational_strengths(e_a_cm, e_b_cm, j_cm, triple_cgs):
    """Return (nu_plus, nu_minus, R_plus, R_minus) for one configuration.

    R is in cgs (erg cm^3). R_plus = -R_minus, so the couplet is conservative.
    """
    e_a, e_b = float(e_a_cm), float(e_b_cm)
    delta = e_a - e_b
    omega = float(np.hypot(delta, 2.0 * j_cm))
    mean = 0.5 * (e_a + e_b)
    nu_plus, nu_minus = mean + 0.5 * omega, mean - 0.5 * omega
    # c_A c_B = +- J / Omega; R_pm = -pi nubar c_A c_B T
    weight = j_cm / omega if omega else 0.0
    r_plus = -np.pi * mean * weight * triple_cgs
    return nu_plus, nu_minus, r_plus, -r_plus


def cd_spectrum(grid_cm, frames, sigma_cm):
    """Ensemble Delta_epsilon (M^-1 cm^-1) on `grid_cm`.

    `frames` yields (e_a_cm, e_b_cm, j_cm, triple_cgs). The Gaussian is
    normalised over wavenumber so that the prefactor convention above holds.
    """
    grid = np.asarray(grid_cm, float)
    out = np.zeros_like(grid)
    norm = 1.0 / (sigma_cm * np.sqrt(2.0 * np.pi))
    count = 0
    for e_a, e_b, j_cm, triple in frames:
        nu_p, nu_m, r_p, r_m = rotational_strengths(e_a, e_b, j_cm, triple)
        for nu, r in ((nu_p, r_p), (nu_m, r_m)):
            shape = norm * np.exp(-0.5 * ((grid - nu) / sigma_cm) ** 2)
            out += DELTA_EPSILON_PREFACTOR * r * nu * shape
        count += 1
    if not count:
        raise ValueError("no frames supplied")
    return out / count


def shift_to_origin(e_a_cm, e_b_cm, origin_cm):
    """Rigidly move the ensemble so its mean site energy sits at `origin_cm`.

    TDDFT places the bright state ~1.07 eV too blue, so an absolute comparison
    needs the band moved onto the experimental origin. The shift is rigid, so it
    leaves every per-configuration detuning E_A - E_B untouched, and it retains
    the spread of the configuration means, which is real inhomogeneous
    broadening rather than an artefact. Do not additionally fold that spread
    into the lineshape width or it is counted twice.
    """
    e_a = np.asarray(e_a_cm, float)
    e_b = np.asarray(e_b_cm, float)
    shift = origin_cm - 0.5 * (e_a + e_b).mean()
    return e_a + shift, e_b + shift


def first_moment(grid_cm, delta_eps):
    """Signed first moment; by the sum rule this is detuning-independent."""
    grid = np.asarray(grid_cm, float)
    return float(np.trapezoid(grid * np.asarray(delta_eps, float), grid))
